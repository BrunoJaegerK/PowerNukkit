package cn.nukkit.network.protocol.types;

public enum AuthInputAction {
    ASCEND, DESCEND, NORTH_JUMP, JUMP_DOWN, SPRINT_DOWN, CHANGE_HEIGHT, JUMPING,
    AUTO_JUMPING_IN_WATER, SNEAKING, SNEAK_DOWN, UP, DOWN, LEFT, RIGHT, UP_LEFT,
    UP_RIGHT, WANT_UP, WANT_DOWN, WANT_DOWN_SLOW, WANT_UP_SLOW, SPRINTING,
    ASCEND_SCAFFOLDING, DESCEND_SCAFFOLDING, SNEAK_TOGGLE_DOWN, PERSIST_SNEAK,
    START_SPRINTING, STOP_SPRINTING, START_SNEAKING, STOP_SNEAKING, START_SWIMMING,
    STOP_SWIMMING, START_JUMPING, START_GLIDING, STOP_GLIDING, PERFORM_ITEM_INTERACTION,
    PERFORM_BLOCK_ACTIONS, PERFORM_ITEM_STACK_REQUEST, HANDLE_TELEPORT, EMOTING,
    MISSED_SWING, START_CRAWLING, STOP_CRAWLING, START_FLYING, STOP_FLYING,
    RECEIVED_SERVER_DATA, IN_CLIENT_PREDICTED_IN_VEHICLE, PADDLE_LEFT, PADDLE_RIGHT,
    BLOCK_BREAKING_DELAY_ENABLED, HORIZONTAL_COLLISION, VERTICAL_COLLISION, DOWN_LEFT,
    DOWN_RIGHT, START_USING_ITEM, IS_CAMERA_RELATIVE_MOVEMENT_ENABLED,
    IS_ROT_CONTROLLED_BY_MOVE_DIRECTION, START_SPIN_ATTACK, STOP_SPIN_ATTACK,
    HOTBAR_ONLY_TOUCH, JUMP_RELEASED_RAW, JUMP_PRESSED_RAW, JUMP_CURRENT_RAW,
    SNEAK_RELEASED_RAW, SNEAK_PRESSED_RAW, SNEAK_CURRENT_RAW, INTERNAL_UPDATE;

    private static final AuthInputAction[] VALUES = values();

    public static AuthInputAction from(int id) {
        if (id < 0 || id >= VALUES.length) {
            throw new IllegalArgumentException("Unknown auth input action: " + id);
        }
        return VALUES[id];
    }

    public static int size() {
        return VALUES.length;
    }
}
